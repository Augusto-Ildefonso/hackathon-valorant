"""Picks showcase entities for the demo (Stream F) from the data. Usage, from the repo root:

    backend/.venv/bin/python backend/scripts/showcase.py

Prints candidates and writes `.claude/docs/showcase-candidates.md`. Criteria: close, long matches with a minimap and
kills with positions (good replay); aces and clutch-like rounds; teams and maps with enough history that no panel is
flagged low-sample; an Action Plan matchup where both teams have played the map.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

import pandas as pd  # noqa: E402

from app.data import catalog  # noqa: E402,F401
from app.deps import get_store  # noqa: E402

store = get_store()
m = store.matches.copy()
k = store.kills

# --- matches: close score, many rounds, kills with positions, an ace in it
m["rounds_played"] = m.score_a + m.score_b
m["margin"] = (m.score_a - m.score_b).abs()
has_pos = k[k.player_locations.map(lambda x: x is not None and len(x) > 0)].groupby("match_id").size().rename("pos_kills")
m = m.merge(has_pos, left_on="match_id", right_index=True, how="left").fillna({"pos_kills": 0})
per_round = k.groupby(["match_id", "killer", "round_num"]).size().reset_index(name="n")
aces = per_round[per_round.n >= 5].groupby("match_id").size().rename("aces")
m = m.merge(aces, left_on="match_id", right_index=True, how="left").fillna({"aces": 0})
mm = m[~m.map_name.isin(["Abyss", "Summit"])]  # these two have no minimap in the catalog
mm = mm.assign(score=-mm.margin * 3 + mm.rounds_played + mm.aces * 4 + (mm.pos_kills > 100) * 5)
matches = mm.sort_values("score", ascending=False).head(5)

# --- teams and the matchup with enough common history on one map
played = pd.concat([m[["match_id", "map_name", "team_a"]].rename(columns={"team_a": "team"}), m[["match_id", "map_name", "team_b"]].rename(columns={"team_b": "team"})])
n_team = played.groupby("team").size().sort_values(ascending=False)
n_map = played.groupby(["team", "map_name"]).size()
pairs = []
top = list(n_team.head(14).index)
for a in top:
    for b in top:
        if a >= b:
            continue
        for mp in sorted(set(played.map_name)):
            if mp in ("Abyss", "Summit"):
                continue
            na, nb = n_map.get((a, mp), 0), n_map.get((b, mp), 0)
            if na >= 3 and nb >= 3:
                pairs.append((min(na, nb), a, b, mp, na, nb))
pairs.sort(reverse=True)

# --- maps: most played with a minimap
maps = m[~m.map_name.isin(["Abyss", "Summit"])].groupby("map_name").size().sort_values(ascending=False)

lines = ["# Showcase candidates (generated by backend/scripts/showcase.py)", "", "## Matches (replay)"]
for _, r in matches.iterrows():
    lines.append(f"- `{r.match_id}` {r.team_a} {r.score_a}x{r.score_b} {r.team_b} on {r.map_name} ({r.tournament}); aces: {int(r.aces)}, kills with positions: {int(r.pos_kills)}")
lines += ["", "## Teams (most matches)"] + [f"- {t}: {n} maps" for t, n in n_team.head(6).items()]
lines += ["", "## Action Plan matchups (both teams played the map at least 3 times)"]
lines += [f"- {a} vs {b} on {mp} ({na} and {nb} maps)" for _, a, b, mp, na, nb in pairs[:6]]
lines += ["", "## Maps with a minimap (most played)"] + [f"- {n}: {c} matches" for n, c in maps.head(4).items()]
text = "\n".join(lines)
print(text)
(ROOT / ".claude/docs/showcase-candidates.md").write_text(text + "\n")
